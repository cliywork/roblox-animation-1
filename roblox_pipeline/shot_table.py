"""
shot_table.py — write docs/SHOTS.md: every shot in scene.py's TIMELINE with its movie span and note.

    python shot_table.py
"""
import contextlib
import io
import os

with contextlib.redirect_stdout(io.StringIO()):          # scene.py prints build diagnostics on import
    import scene

FPS = 23.976
out = os.path.join(scene.HERE, "..", "docs", "SHOTS.md")
rows = ["# Shots (generated by roblox_pipeline/shot_table.py — do not edit)", "",
        "| Shot | Movie start | Dur | Frames | Flags | Note |", "|---|---|---|---|---|---|"]
for sh in scene.TIMELINE:
    f0, f1 = round(sh["start"] * FPS), round((sh["start"] + sh["dur"]) * FPS)
    flags = " ".join(x for x in (f'hud={sh["hud"]}' if sh.get("hud") else "", f'hide={sh["hide"]}' if sh.get("hide") else "") if x)
    rows.append(f'| {sh["shot"]} | {sh["start"]:.3f} | {sh["dur"]:.3f} | {f0}–{f1} | {flags} | {sh["note"]} |')
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(rows) + "\n")
print("wrote", os.path.normpath(out), len(scene.TIMELINE), "shots")
